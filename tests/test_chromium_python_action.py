import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

RUNNER = (Path(__file__).resolve().parents[1] /
          'overlays/chromium/bcr/overlay/native/python_action.py')


class ChromiumPythonActionTest(unittest.TestCase):
    def test_execroot_scratch_is_private_and_removed_after_generation(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            (root / 'generator.py').write_text(
                'import pathlib\npathlib.Path("result.txt").write_text(str(pathlib.Path.cwd()))\n')
            manifest = {'inputs': [['generator.py', 'scripts/generator.py']],
                        'outputs': [['result.txt', 'result.txt']], 'build_dir': 'out/import',
                        'script': 'scripts/generator.py', 'args': [], 'response_file_contents': [],
                        'scratch_in_execroot': True}
            (root / 'manifest.json').write_text(json.dumps(manifest))
            result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                    cwd=root, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertTrue(Path((root / 'result.txt').read_text()).is_relative_to(root))
            self.assertEqual(list(root.glob('chromium-action-*')), [])

    def test_generated_provenance_is_stable_across_execution_roots(self):
        with tempfile.TemporaryDirectory() as directory:
            outputs = []
            for attempt in ('one', 'two'):
                root = Path(directory) / attempt
                root.mkdir()
                (root / 'generator.py').write_text(
                    'import pathlib, sys\n'
                    'pathlib.Path("gen/result.cc").write_text('
                    '"// Generated by " + sys.argv[0] + "\\n" + '
                    '"// Response " + sys.argv[1] + "\\n" + '
                    'pathlib.Path(sys.argv[1]).read_text())\n')
                manifest = {
                    'scratch_in_execroot': attempt == 'two',
                    'inputs': [['generator.py', 'tools/flags/generator.py']],
                    'outputs': [['result.cc', 'gen/result.cc']],
                    'build_dir': 'out/import', 'script': 'tools/flags/generator.py',
                    'args': ['{{response_file_name}}'], 'response_file_contents': ['same input'],
                }
                (root / 'manifest.json').write_text(json.dumps(manifest))
                result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                        cwd=root, capture_output=True, text=True)
                self.assertEqual(result.returncode, 0, result.stderr)
                outputs.append((root / 'result.cc').read_text())
            self.assertEqual(outputs[0], outputs[1])
            self.assertEqual(outputs[0], '// Generated by ../../tools/flags/generator.py\n'
                             '// Response action.rsp\n\'same input\'')

    def test_stages_imports_response_file_and_multiple_outputs(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / 'helper.py').write_text('VALUE = "declared import"\n')
            (root / 'generator.py').write_text('''import helper, pathlib, shlex, sys
arguments = shlex.split(pathlib.Path(sys.argv[1]).read_text())
pathlib.Path('gen/first.txt').write_text(helper.VALUE)
pathlib.Path('gen/second.txt').write_text(arguments[0])
''')
            manifest = {
                'inputs': [['generator.py', 'scripts/generator.py'],
                           ['helper.py', 'scripts/helper.py']],
                'outputs': [['first.txt', 'gen/first.txt'],
                            ['second.txt', 'gen/second.txt']],
                'build_dir': 'out/import',
                'script': 'scripts/generator.py',
                'args': ['{{response_file_name}}'],
                'response_file_contents': ['LABEL="contains spaces"'],
            }
            (root / 'manifest.json').write_text(json.dumps(manifest))
            result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                    cwd=root, capture_output=True, text=True,
                                    env=dict(os.environ, PYTHONSAFEPATH='1'))
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual((root / 'first.txt').read_text(), 'declared import')
            self.assertEqual((root / 'second.txt').read_text(), 'LABEL="contains spaces"')

    def test_preserves_multicall_tool_name(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / 'llvm').write_text(
                '#!' + sys.executable + '\nimport pathlib, sys\n'
                'pathlib.Path(sys.argv[1]).write_text(pathlib.Path(sys.argv[0]).name)\n')
            (root / 'llvm').chmod(0o755)
            (root / 'clang').symlink_to('llvm')
            (root / 'generator.py').write_text(
                'import subprocess\n'
                'subprocess.run(["../../tools/clang", "gen/tool.txt"], check=True)\n')
            manifest = {
                'inputs': [['generator.py', 'scripts/generator.py'], ['clang', 'tools/clang']],
                'executable_inputs': ['tools/clang'],
                'outputs': [['tool.txt', 'gen/tool.txt']],
                'build_dir': 'out/import', 'script': 'scripts/generator.py',
                'args': [], 'response_file_contents': [],
            }
            (root / 'manifest.json').write_text(json.dumps(manifest))
            result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                    cwd=root, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual((root / 'tool.txt').read_text(), 'clang')

    def test_rejects_output_path_escape(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            manifest = {'inputs': [], 'build_dir': 'out/import',
                        'outputs': [['result', '../../escape']]}
            (root / 'manifest.json').write_text(json.dumps(manifest))
            result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                    cwd=root, capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn('invalid logical path', result.stderr)
            self.assertFalse((root / 'escape').exists())


if __name__ == '__main__':
    unittest.main()
