import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

RUNNER = (Path(__file__).resolve().parents[1] /
          'overlays/chromium/bcr/overlay/native/python_action.py')


class ChromiumPythonActionTest(unittest.TestCase):
    def test_generated_provenance_is_stable_across_execution_roots(self):
        with tempfile.TemporaryDirectory() as directory:
            outputs = []
            for attempt in ('one', 'two'):
                root = Path(directory) / attempt
                root.mkdir()
                (root / 'generator.py').write_text(
                    'import pathlib, sys\n'
                    'pathlib.Path("gen/result.cc").write_text('
                    '"// Generated by " + sys.argv[0] + "\\n" + '
                    '"// Response " + sys.argv[1] + "\\n" + '
                    'pathlib.Path(sys.argv[1]).read_text())\n')
                manifest = {
                    'inputs': [['generator.py', 'tools/flags/generator.py']],
                    'outputs': [['result.cc', 'gen/result.cc']],
                    'build_dir': 'out/import', 'script': 'tools/flags/generator.py',
                    'args': ['{{response_file_name}}'], 'response_file_contents': ['same input'],
                }
                (root / 'manifest.json').write_text(json.dumps(manifest))
                result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                        cwd=root, capture_output=True, text=True)
                self.assertEqual(result.returncode, 0, result.stderr)
                outputs.append((root / 'result.cc').read_text())
            self.assertEqual(outputs[0], outputs[1])
            self.assertEqual(outputs[0], '// Generated by ../../tools/flags/generator.py\n'
                             '// Response action.rsp\n\'same input\'')

    def test_stages_imports_response_file_and_multiple_outputs(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / 'helper.py').write_text('VALUE = "declared import"\n')
            (root / 'generator.py').write_text('''import helper, pathlib, shlex, sys
arguments = shlex.split(pathlib.Path(sys.argv[1]).read_text())
pathlib.Path('gen/first.txt').write_text(helper.VALUE)
pathlib.Path('gen/second.txt').write_text(arguments[0])
''')
            manifest = {
                'inputs': [['generator.py', 'scripts/generator.py'],
                           ['helper.py', 'scripts/helper.py']],
                'outputs': [['first.txt', 'gen/first.txt'],
                            ['second.txt', 'gen/second.txt']],
                'build_dir': 'out/import',
                'script': 'scripts/generator.py',
                'args': ['{{response_file_name}}'],
                'response_file_contents': ['LABEL="contains spaces"'],
            }
            (root / 'manifest.json').write_text(json.dumps(manifest))
            result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                    cwd=root, capture_output=True, text=True,
                                    env=dict(os.environ, PYTHONSAFEPATH='1'))
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual((root / 'first.txt').read_text(), 'declared import')
            self.assertEqual((root / 'second.txt').read_text(), 'LABEL="contains spaces"')

    def test_preserves_multicall_tool_name(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / 'llvm').write_text(
                '#!' + sys.executable + '\nimport pathlib, sys\n'
                'pathlib.Path(sys.argv[1]).write_text(pathlib.Path(sys.argv[0]).name)\n')
            (root / 'llvm').chmod(0o755)
            (root / 'clang').symlink_to('llvm')
            (root / 'generator.py').write_text(
                'import subprocess\n'
                'subprocess.run(["../../tools/clang", "gen/tool.txt"], check=True)\n')
            manifest = {
                'inputs': [['generator.py', 'scripts/generator.py'], ['clang', 'tools/clang']],
                'executable_inputs': ['tools/clang'],
                'outputs': [['tool.txt', 'gen/tool.txt']],
                'build_dir': 'out/import', 'script': 'scripts/generator.py',
                'args': [], 'response_file_contents': [],
            }
            (root / 'manifest.json').write_text(json.dumps(manifest))
            result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                    cwd=root, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual((root / 'tool.txt').read_text(), 'clang')

    @unittest.skipUnless(Path('/bin/sh').exists(), 'POSIX native executable')
    def test_explicit_invocation_name_survives_staging(self):
        with tempfile.TemporaryDirectory() as directory:
            outputs = []
            for attempt in ('first', 'different path'):
                root = Path(directory) / attempt
                root.mkdir()
                (root / 'native-tool').symlink_to('/bin/sh')
                (root / 'generator.py').write_text(
                    'import pathlib, subprocess\n'
                    'result = subprocess.run(["../../tools/gperf", "-c", '
                    '\'printf "%s" "$0"\'], check=True, capture_output=True)\n'
                    'pathlib.Path("result.txt").write_bytes(result.stdout)\n')
                manifest = {
                    'inputs': [['generator.py', 'scripts/generator.py'], ['native-tool', 'tools/gperf']],
                    'executable_inputs': ['tools/gperf'],
                    'executable_names': {'tools/gperf': 'gperf'},
                    'outputs': [['result.txt', 'result.txt']],
                    'build_dir': 'out/import', 'script': 'scripts/generator.py',
                    'args': [], 'response_file_contents': [],
                }
                (root / 'manifest.json').write_text(json.dumps(manifest))
                result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                        cwd=root, capture_output=True, text=True)
                self.assertEqual(result.returncode, 0, result.stderr)
                outputs.append((root / 'result.txt').read_text())
            self.assertEqual(outputs, ['gperf', 'gperf'])

    def _run_tree_alias_action(self, root, alias_contents):
        package = root / 'packages/@lit/core'
        package.mkdir(parents=True)
        (package / 'index.d.ts').write_text('original declaration')
        (package / 'index.d.ts').chmod(0o555)
        (root / 'alias.d.ts').write_text(alias_contents)
        (root / 'alias.d.ts').chmod(0o640)
        (root / 'extra.d.ts').write_text('additional declaration')
        (root / 'generator.py').write_text("import json, pathlib, stat\npackage = pathlib.Path('../../third_party/node/node_modules/@lit/core')\nresult = {\n    'existing': (package / 'index.d.ts').read_text(),\n    'extra': (package / 'extra.d.ts').read_text(),\n    'permissions': stat.S_IMODE((package / 'index.d.ts').stat().st_mode),\n}\npathlib.Path('result.json').write_text(json.dumps(result))\n")
        logical = 'third_party/node/node_modules'
        manifest = {
            'inputs': [['packages', logical], ['alias.d.ts', logical + '/@lit/core/index.d.ts'],
                       ['extra.d.ts', logical + '/@lit/core/extra.d.ts'],
                       ['generator.py', 'tools/generator.py']],
            'outputs': [['result.json', 'result.json']],
            'build_dir': 'out/import', 'script': 'tools/generator.py',
            'args': [], 'response_file_contents': [], 'preserve_node_symlinks': True,
        }
        (root / 'manifest.json').write_text(json.dumps(manifest))
        return subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                              cwd=root, capture_output=True, text=True)

    @unittest.skipUnless(os.name == 'posix', 'POSIX file permissions')
    def test_tree_alias_preserves_permissions_and_adds_files_privately(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            result = self._run_tree_alias_action(root, 'original declaration')
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(json.loads((root / 'result.json').read_text()), {
                'existing': 'original declaration', 'extra': 'additional declaration',
                'permissions': 0o640,
            })
            self.assertFalse((root / 'packages/@lit/core/extra.d.ts').exists())
            original = root / 'packages/@lit/core/index.d.ts'
            self.assertEqual(original.read_text(), 'original declaration')
            self.assertEqual(original.stat().st_mode & 0o777, 0o555)

    @unittest.skipUnless(os.name == 'posix', 'POSIX file permissions')
    def test_tree_alias_conflict_rejects_generation_without_changing_input(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            result = self._run_tree_alias_action(root, 'conflicting declaration')
            self.assertNotEqual(result.returncode, 0)
            self.assertIn('conflicting logical input inside declared directory', result.stderr)
            self.assertFalse((root / 'result.json').exists())
            self.assertEqual((root / 'packages/@lit/core/index.d.ts').read_text(),
                             'original declaration')
            self.assertFalse((root / 'packages/@lit/core/extra.d.ts').exists())

    def test_rejects_output_path_escape(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            manifest = {'inputs': [], 'build_dir': 'out/import',
                        'outputs': [['result', '../../escape']]}
            (root / 'manifest.json').write_text(json.dumps(manifest))
            result = subprocess.run([sys.executable, str(RUNNER), 'manifest.json'],
                                    cwd=root, capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn('invalid logical path', result.stderr)
            self.assertFalse((root / 'escape').exists())


if __name__ == '__main__':
    unittest.main()
