#!/usr/bin/env python3
"""Import Perfetto's browser runtime generators and compile its real SDK graph."""
import gzip
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
PREFIX = '//third_party/perfetto/'
BUILD = '//out/bazel-import/'


def main():
    graph = json.loads(gzip.decompress(Path(sys.argv[1]).read_bytes()))
    source = Path(sys.argv[2])
    if not (source / 'python/generators/trace_processor_table/public.py').is_file():
        raise ValueError('expected the Perfetto source root as the second argument')
    targets = graph['targets']
    seen, pending = set(), ['//third_party/perfetto:libperfetto']
    while pending:
        label = pending.pop()
        if label in seen or not label.startswith(PREFIX[:-1]):
            continue
        seen.add(label)
        target = targets[label]
        if target['type'] != 'executable':
            pending.extend(target.get('deps', []))
    actions = {label: targets[label] for label in sorted(seen)
               if targets[label]['type'] == 'action'
               and targets[label]['script'] not in ('//tools/protoc_wrapper/protoc_wrapper.py', PREFIX + 'gn/write_buildflag_header.py')}
    names = {label: 'perfetto_runtime_' + hashlib.sha256(label.encode()).hexdigest()[:16] for label in actions}
    proto = json.loads((ROOT / 'bcr/overlay/native/perfetto_proto_targets.json').read_text())
    python = sorted(PREFIX + str(path.relative_to(source)) for directory in ('python/generators/trace_processor_table', 'src/trace_processor/tables') for path in (source / directory).rglob('*.py'))
    lines = ['"""Generated by tools/import_perfetto_runtime.py from browser graph."""', '',
             'load("@perfetto//bazel:chromium_sdk.bzl", "chromium_sdk")',
             'load(":python_action.bzl", "chromium_python_action")',
             'load(":shared_prefix_consumers.bzl", "shared_prefix_library")', '',
             'def native_perfetto_runtime(name):', '    """Generate tables/descriptors and compile real browser tracing runtime.', '',
             '    Args:', '        name: SDK library target.', '    """']
    generated_headers = []
    for label, target in actions.items():
        files, deps = {}, []
        inputs = set(target.get('inputs', []) + target.get('sources', []) + [target['script']])
        if target['script'].endswith('/gen_tp_table_headers.py'):
            inputs.update(python)
        for path in sorted(inputs):
            if path.startswith(BUILD):
                file = ':' + path.removeprefix(BUILD)
            elif path.startswith(PREFIX):
                relative = path.removeprefix(PREFIX)
                file = '@perfetto//python:' + relative.removeprefix('python/') if relative.startswith('python/') else '@perfetto//:' + relative
            else:
                raise ValueError(f'unmapped runtime generator input: {path}')
            files[file] = path[2:]
        for dependency in target.get('deps', []):
            if dependency in names:
                deps.append(':' + names[dependency])
            elif dependency in proto:
                deps.append(':' + proto[dependency])
            else:
                raise ValueError(f'unmapped runtime generator dependency: {dependency}')
        if any(not path.startswith(BUILD) for path in target['outputs']):
            raise ValueError(f'unsupported runtime outputs: {label}')
        outputs = {path.removeprefix(BUILD): path.removeprefix(BUILD) for path in target['outputs']}
        generated_headers += [':' + path for path in outputs if path.endswith('.h')]
        lines += ['    chromium_python_action(', '        name = ' + json.dumps(names[label]) + ',',
                  '        srcs = ' + json.dumps(files) + ',', '        outs = ' + json.dumps(outputs) + ',',
                  '        script = ' + json.dumps(target['script'][2:]) + ',',
                  '        args = ' + json.dumps(target['args']) + ',',
                  '        deps = ' + json.dumps(deps) + ',', '    )']
    ipc = sorted({path.removeprefix(BUILD) for label in seen for path in targets[label].get('sources', []) if path.startswith(BUILD) and path.endswith('.ipc.cc')})
    generated_headers += [':' + path.removesuffix('.cc') + '.h' for path in ipc]
    lines += ['    chromium_sdk(', '        name = name,', '        library_rule = shared_prefix_library,', '        protocol_library = ":perfetto_proto_cpp",',
              '        generated_sources = ' + json.dumps([':' + path for path in ipc]) + ',',
              '        generated_headers = ' + json.dumps(sorted(set(generated_headers))) + ',', '    )', '']
    (ROOT / 'bcr/overlay/native/perfetto_runtime.bzl').write_text('\n'.join(lines))
    print(f'Imported {len(actions)} runtime generators, {len(ipc)} IPC C++ sources, {len(generated_headers)} generated headers')


if __name__ == '__main__':
    main()
